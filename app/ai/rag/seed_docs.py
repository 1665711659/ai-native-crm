async def ensure_kb_seed(db) -> int:
    """kb_documents 为空时导入种子知识，返回导入条数。"""
    row = await db.fetch_one("SELECT COUNT(*) AS c FROM kb_documents")
    if row and row["c"] > 0:
        return 0
    from datetime import datetime
    now = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    for doc in SEED_KB_DOCS:
        await db.execute(
            "INSERT INTO kb_documents (title, content, source, created_at) VALUES (?,?,?,?)",
            (doc["title"], doc["content"], doc.get("source", ""), now),
        )
    return len(SEED_KB_DOCS)
